"""Score field-by-field extraction accuracy on the synthetic invoice set.

Always uses the offline mock provider, whatever LLM_PROVIDER says, so it never calls an API.
A null value where the ground truth is null counts as correct: refusing to guess is right.

Usage: python scripts/eval_extraction.py [--data-dir data] [--out-dir docs]
Writes eval-report.json and eval-report.md to the output directory.
"""

import argparse
import json
import sys
from collections import Counter, defaultdict
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))  # lets `python scripts/eval_extraction.py` import the app

from app.services.llm.mock import MockProvider
from app.services.pdf_extract import extract_text

FIELDS = ["vendor_name", "invoice_number", "invoice_date", "total", "po_number"]


def _as_text(value) -> str | None:
    if value is None:
        return None
    return value.isoformat() if hasattr(value, "isoformat") else str(value)


def score_field(field: str, expected, extracted) -> bool:
    """True when the extracted value matches the ground truth (null == null is correct)."""
    if expected is None or extracted is None:
        return expected is None and extracted is None
    if field == "total":
        return Decimal(str(expected)) == Decimal(str(extracted))
    return _as_text(expected).strip() == _as_text(extracted).strip()


def _evaluate_invoice(provider: MockProvider, pdf_path: Path, truth: dict) -> dict:
    extraction = provider.extract(extract_text(pdf_path.read_bytes()))
    fields = {}
    for field in FIELDS:
        extracted = getattr(extraction, field)
        fields[field] = {
            "expected": truth[field],
            "extracted": _as_text(extracted),
            "correct": score_field(field, truth[field], extracted),
        }
    return {
        "filename": pdf_path.name,
        "case_type": truth["case_type"],
        "fields": fields,
        "tokens": provider.last_token_usage,
    }


def _summarize(results: list[dict]) -> dict:
    field_accuracy, refusals = {}, {}
    for field in FIELDS:
        scores = [r["fields"][field] for r in results]
        correct = sum(s["correct"] for s in scores)
        field_accuracy[field] = {
            "correct": correct,
            "total": len(scores),
            "accuracy": round(correct / len(scores), 4) if scores else 0.0,
        }
        refusals[field] = {
            "correct_refusals": sum(
                s["expected"] is None and s["extracted"] is None for s in scores
            ),
            "wrong_guesses": sum(
                s["expected"] is None and s["extracted"] is not None for s in scores
            ),
            "misses": sum(s["expected"] is not None and s["extracted"] is None for s in scores),
        }
    by_case: dict = defaultdict(Counter)
    for r in results:
        by_case[r["case_type"]]["invoices"] += 1
        by_case[r["case_type"]]["all_fields_correct"] += all(
            s["correct"] for s in r["fields"].values()
        )
    return {
        "field_accuracy": field_accuracy,
        "refusals": refusals,
        "by_case_type": {case: dict(counts) for case, counts in sorted(by_case.items())},
    }


def run_eval(data_dir: Path | str, out_dir: Path | str) -> dict:
    data_dir, out_dir = Path(data_dir), Path(out_dir)
    ground_truth = json.loads((data_dir / "ground_truth.json").read_text())
    provider = MockProvider()
    results = [
        _evaluate_invoice(provider, data_dir / "invoices" / filename, truth)
        for filename, truth in sorted(ground_truth.items())
    ]
    report = {
        "provider": provider.name,
        "invoice_count": len(results),
        **_summarize(results),
        "token_usage": {"total_tokens": sum(r["tokens"] for r in results)},
        "invoices": results,
    }
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "eval-report.json").write_text(json.dumps(report, indent=2) + "\n")
    (out_dir / "eval-report.md").write_text(render_markdown(report))
    return report


def render_markdown(report: dict) -> str:
    lines = [
        "# Extraction eval report",
        "",
        "Generated by `scripts/eval_extraction.py`. Every number below comes from that script.",
        "",
        f"- Provider: `{report['provider']}` (offline, deterministic; no API calls)",
        (
            f"- Dataset: {report['invoice_count']} synthetic invoice PDFs scored against "
            "`data/ground_truth.json`"
        ),
        (
            "- Scoring: exact match per field after trimming; totals compare as decimals. "
            "A null where the ground truth is null counts as correct, because refusing to guess "
            "a missing value is the right behaviour."
        ),
        "",
        "## Per-field accuracy",
        "",
        "| Field | Correct | Total | Accuracy |",
        "|---|---|---|---|",
    ]
    for field, stats in report["field_accuracy"].items():
        lines.append(
            f"| {field} | {stats['correct']} | {stats['total']} | {stats['accuracy']:.1%} |"
        )
    lines += [
        "",
        "## Missing values",
        "",
        "| Field | Correct refusals (null = null) | Wrong guesses | Misses |",
        "|---|---|---|---|",
    ]
    for field, r in report["refusals"].items():
        lines.append(
            f"| {field} | {r['correct_refusals']} | {r['wrong_guesses']} | {r['misses']} |"
        )
    lines += ["", "## Results by case type", "", "| Case type | Invoices | All 5 fields correct |"]
    lines.append("|---|---|---|")
    for case, counts in report["by_case_type"].items():
        lines.append(f"| {case} | {counts['invoices']} | {counts['all_fields_correct']} |")

    mismatches = [
        f"- `{r['filename']}` ({r['case_type']}) {field}: expected `{s['expected']}`, "
        f"extracted `{s['extracted']}`"
        for r in report["invoices"]
        for field, s in r["fields"].items()
        if not s["correct"]
    ]
    lines += ["", "## Mismatches", "", *(mismatches or ["None."])]
    lines += [
        "",
        "## Cost and tokens",
        "",
        (
            f"- Tokens used in this run: {report['token_usage']['total_tokens']} "
            "(the mock provider makes no API calls, so cost is $0)."
        ),
        (
            "- With a real provider, each `extract()` call stores the tokens the API reports in "
            "`provider.last_token_usage`, and ingestion writes it as `token_usage` in the "
            "`invoice_ingested` JSON log line, next to `invoice_id`, `provider`, and `elapsed_ms`."
        ),
        (
            "- The APIs report prompt and completion tokens separately: OpenAI "
            "`usage.input_tokens` / `usage.output_tokens`, Anthropic `usage.input_tokens` / "
            "`usage.output_tokens`, Gemini `usage_metadata.prompt_token_count` / "
            "`candidates_token_count`. The app currently logs their sum. Summing `token_usage` "
            "across log lines and multiplying by the provider's per-token price gives the cost."
        ),
        "",
        "## Limits",
        "",
        (
            "- The mock is a parser written for this exact synthetic template, so these numbers "
            "show that the pipeline and scoring work. They are not a measure of real LLM accuracy."
        ),
        "- Real-provider accuracy needs an API key and is not run in tests or CI.",
        "",
        "## Reproduce",
        "",
        "```bash",
        ".venv/bin/python scripts/eval_extraction.py",
        "```",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--data-dir", default=ROOT / "data", type=Path)
    parser.add_argument("--out-dir", default=ROOT / "docs", type=Path)
    args = parser.parse_args(argv)

    report = run_eval(args.data_dir, args.out_dir)
    print(f"Evaluated {report['invoice_count']} invoices with the {report['provider']} provider")
    print("Per-field accuracy:")
    for field, stats in report["field_accuracy"].items():
        print(f"  {field:<15} {stats['correct']}/{stats['total']}  {stats['accuracy']:.1%}")
    print(f"Tokens used: {report['token_usage']['total_tokens']}")
    print(f"Report written to {args.out_dir / 'eval-report.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
